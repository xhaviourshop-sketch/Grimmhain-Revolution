/** Kurzform: deutsche Quelltexte für UI; im Modus EN nach translateRuntimeText, sonst unverändert. */
window.tUi = function(text) {
  if (typeof text !== "string") return text;
  return window.translateRuntimeText ? window.translateRuntimeText(text) : text;
};

window.translateElementTree = function(root) {
  if (!root || (localStorage.getItem("grimmhain_lang") || "de") !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  let node = walker.nextNode();
  while (node) {
    const oldVal = node.nodeValue;
    const newVal = window.translateRuntimeText(oldVal);
    if (newVal !== oldVal) node.nodeValue = newVal;
    node = walker.nextNode();
  }
};

window.translateDynamicSections = function() {
  if (window.__translating) return;
  window.__translating = true;
  try {
    const ids = ["overlay","pickbar","logOverlay","setupModal","privateRoleOverlay","order","rolePicker","pop"];
    ids.forEach(function(id){
      const el = document.getElementById(id);
      if (el) window.translateElementTree(el);
    });
  } finally {
    window.__translating = false;
  }
};

window.installI18nObserver = function() {
  if (window.__i18nObserverInstalled) {
    window.translateDynamicSections();
    return;
  }
  window.__i18nObserverInstalled = true;
  const obs = new MutationObserver(function(){
    window.translateDynamicSections();
  });
  obs.observe(document.body, { childList:true, subtree:true, characterData:false });
  window.__i18nObserver = obs;
  window.translateDynamicSections();
};

window.addEventListener("beforeunload", function(){
  try{
    if(window.__i18nObserver && typeof window.__i18nObserver.disconnect === "function"){
      window.__i18nObserver.disconnect();
    }
    window.__i18nObserver = null;
    window.__i18nObserverInstalled = false;
  }catch(e){}
});
