window.t = function(key) {
  const lang = localStorage.getItem("grimmhain_lang") || "de";
  return (window.I18N[lang] && window.I18N[lang][key]) || key;
};

window.tf = function(key, vars) {
  let out = window.t(key);
  if (!vars) return out;
  Object.keys(vars).forEach(function(k) {
    out = out.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
  });
  return out;
};

window.setLang = function(lang) {
  localStorage.setItem("grimmhain_lang", lang);
  applyTranslations();
  try {
    if (typeof draw === "function") draw();
    if (typeof rebuildOrder === "function") rebuildOrder();
    if (typeof renderLog === "function") renderLog();
    if (typeof window.installI18nObserver === "function") window.installI18nObserver();
  } catch (e) {}
};

window.applyTranslations = function() {
  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    const key = el.getAttribute("data-i18n");
    el.textContent = window.t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", window.t(key));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-title");
    el.setAttribute("title", window.t(key));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-aria-label");
    el.setAttribute("aria-label", window.t(key));
  });
  const btn = document.getElementById("langToggleBtn");
  const lang = localStorage.getItem("grimmhain_lang") || "de";
  if (btn) btn.textContent = lang === "de" ? "DE" : "ENG";
  if (typeof window.translateDynamicSections === "function") window.translateDynamicSections();
};

